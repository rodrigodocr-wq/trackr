export function getLocale(shopDomain?: string): Locale {
  const brDomains = (process.env.SHOPIFY_BR_DOMAINS || '').split(',').map(d => d.trim()).filter(Boolean)
  if (shopDomain && brDomains.includes(shopDomain)) return 'pt-BR'
  return 'en-GB'
}

export function t(locale: Locale) {
  return translations[locale]
}
